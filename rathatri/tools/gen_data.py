#!/usr/bin/env python3
"""Generate parts/p30c_lore_data.js from docs/lore/*.json (codex entries, loading quotes, barks, cutscene scripts).
Run before build whenever the lore JSON changes:  python3 tools/gen_data.py"""
import json, glob, os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
lore = os.path.join(root, 'docs', 'lore')
codex = {}
for f in sorted(glob.glob(os.path.join(lore, 'codex_*.json'))):
    for e in json.load(open(f)):
        if e['id'] in codex: print('dup codex id', e['id'], file=sys.stderr)
        codex[e['id']] = {'id': e['id'], 'cat': e['cat'], 'title': e['title'], 'text': e['text']}
sc = json.load(open(os.path.join(lore, 'script.json')))
scenes = {s['id']: s for s in sc['scenes']}
out = {'codex': codex, 'quotes': sc['loading_quotes'], 'barks': sc['barks'], 'scenes': scenes}
js = '/* GENERATED by tools/gen_data.py from docs/lore/*.json — do not edit by hand. */\nconst LORE = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029') + ';\n'
open(os.path.join(root, 'parts', 'p30c_lore_data.js'), 'w').write(js)
print('p30c_lore_data.js', len(js), 'bytes;', len(codex), 'codex,', len(scenes), 'scenes,', len(sc['loading_quotes']), 'quotes')
